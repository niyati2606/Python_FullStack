my_string = "Python Programming"

print(f"Original string: {my_string}")
print(f"First 6 characters: {my_string[:6]}")
print(f"From index 7 onwards: {my_string[7:]}")
print(f"Characters 7 to 10: {my_string[7:11]}")
print(f"Last character: {my_string[-1]}")
print(f"Last 11 characters: {my_string[-11:]}")
print(f"Every 2nd character: {my_string[::2]}")
print(f"Reversed string: {my_string[::-1]}")
